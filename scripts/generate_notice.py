#!/usr/bin/env python3
"""Render a plain-text OSS attribution/NOTICE document from Yocto SPDX 3.0 SBOMs.

Reads the SPDX 3.0.1 JSON-LD files produced by OpenEmbedded-core's
create-spdx-3.0.bbclass (one @graph per image/SDK), resolves each package's
concluded license expression to full license text, and writes one combined
NOTICE file.

This intentionally parses the JSON-LD @graph directly with the stdlib `json`
module instead of importing bitbake's `oe.spdx30.model`. That module is
auto-generated by shacl2code and marked "DO NOT MANUALLY MODIFY" in oe-core, so
its API is an internal implementation detail, not a stable contract -- and
staying independent of it means this script has no bitbake/Yocto runtime
dependency at all and can be run and tested standalone.

Usage:
    generate_notice.py --common-license-dir DIR -o NOTICE.txt \\
        input1.spdx.json [input2.spdx.json ...]
"""

import argparse
import json
import re
import sys
from pathlib import Path

# Splits a compound SPDX license expression into individual license/exception
# tokens, e.g. "GPL-2.0-only WITH Classpath-exception-2.0" or "(MIT OR Apache-2.0)".
_EXPR_SPLIT_RE = re.compile(r"[()]|\s+(?:AND|OR|WITH)\s+")

# Proprietary / non-distributable license identifiers. A package whose concluded
# license resolves to nothing but these carries no third-party text and is
# omitted entirely -- this file is a third-party notice. OE-core's create-spdx-3.0
# encodes a recipe's LICENSE = "CLOSED" as the SPDX expression literal "NONE" (and
# uses "NOASSERTION" when no license could be determined), so both belong here
# too -- our own closed components must not surface in a third-party notice.
# create-spdx-3.0 may also emit a recipe LICENSE = "Proprietary" as the SPDX
# custom-ref form "LicenseRef-Proprietary", so a token is treated as closed
# either bare or with a leading "LicenseRef-" (see _is_closed_token); this does
# not affect real refs such as LicenseRef-PD, whose stripped form isn't listed.
_CLOSED_TOKENS = {"CLOSED", "Proprietary", "NONE", "NOASSERTION"}

_LICENSEREF_PREFIX = "LicenseRef-"


def _is_closed_token(token):
    if token in _CLOSED_TOKENS:
        return True
    if token.startswith(_LICENSEREF_PREFIX):
        return token[len(_LICENSEREF_PREFIX):] in _CLOSED_TOKENS
    return False

# poky's common-licenses GPL-3.0-with-*-exception files are placeholders whose
# first body line is the literal "insert GPL v3 text here"; strip it.
_PLACEHOLDER_LINE = "insert GPL v3 text here"


def load_graph(path):
    with open(path) as f:
        doc = json.load(f)
    return doc.get("@graph", [])


def index_by_id(graph):
    return {node["spdxId"]: node for node in graph if "spdxId" in node}


def concluded_license_ids_by_package(graph):
    """Map package spdxId -> list of license-node spdxIds via hasConcludedLicense relationships."""
    result = {}
    for node in graph:
        if node.get("type") != "Relationship":
            continue
        if node.get("relationshipType") != "hasConcludedLicense":
            continue
        result.setdefault(node["from"], []).extend(node.get("to") or [])
    return result


def split_expression(expr):
    tokens = [t.strip() for t in _EXPR_SPLIT_RE.split(expr)]
    return [t for t in tokens if t]


def _strip_placeholder(text):
    return "".join(l for l in text.splitlines(keepends=True)
                   if l.strip() != _PLACEHOLDER_LINE)


def resolve_license_text(token, license_expr_node, by_id, common_license_dir, missing):
    """Resolve a single license/exception token to its full text, or None if unresolved."""
    if token.startswith("LicenseRef-"):
        for entry in license_expr_node.get("simplelicensing_customIdToUri", []):
            if entry.get("key") == token:
                text_node = by_id.get(entry.get("value"))
                if text_node is not None:
                    text = text_node.get("simplelicensing_licenseText")
                    if text:
                        return text
        # Unmapped, dangling, or empty-text refs all count as unresolved so a
        # dropped custom license surfaces in the summary (and fails --strict).
        missing.add(token)
        return None

    license_file = common_license_dir / token
    if license_file.is_file():
        return license_file.read_text(errors="replace")

    # Common license files are keyed by the exact SPDX ID; strip a trailing
    # "+" (legacy "-or-later" style shorthand) as a fallback lookup only.
    if token.endswith("+"):
        alt_file = common_license_dir / token[:-1]
        if alt_file.is_file():
            return alt_file.read_text(errors="replace")

    missing.add(token)
    return None


def collect_packages(graph, by_id):
    concluded = concluded_license_ids_by_package(graph)
    packages = []
    for node in graph:
        if node.get("type") != "software_Package":
            continue
        name = node.get("name", "<unknown>")
        version = node.get("software_packageVersion", "")
        license_ids = concluded.get(node["spdxId"], [])
        packages.append((name, version, license_ids))
    return packages


def render_notice(inputs, common_license_dir, out_path, title=None, revision=None):
    missing = set()
    seen_packages = set()
    sections = []

    for input_path in inputs:
        graph = load_graph(input_path)
        by_id = index_by_id(graph)
        for name, version, license_ids in sorted(collect_packages(graph, by_id)):
            key = (name, version)
            if key in seen_packages:
                continue
            seen_packages.add(key)

            license_texts = []
            expressions = []
            tokens = []
            for lic_id in license_ids:
                lic_node = by_id.get(lic_id)
                if lic_node is None or lic_node.get("type") != "simplelicensing_LicenseExpression":
                    continue
                expr = lic_node.get("simplelicensing_licenseExpression", "")
                expressions.append(expr)
                for token in split_expression(expr):
                    tokens.append(token)
                    # CLOSED/Proprietary carry no distributable text; the package
                    # is dropped below, so don't count them as "unresolved".
                    if _is_closed_token(token):
                        continue
                    text = resolve_license_text(token, lic_node, by_id, common_license_dir, missing)
                    if text:
                        license_texts.append((token, _strip_placeholder(text)))

            # Omit packages whose concluded license carries no third-party text
            # (our own proprietary/CLOSED components). This is a third-party notice.
            if not [t for t in tokens if not _is_closed_token(t)]:
                seen_packages.discard(key)
                continue

            header = "Package: %s:%s" % (name, version)
            if expressions:
                header += "\nLicense: %s" % " AND ".join(expressions)

            body = [header, ""]
            if license_texts:
                for token, text in license_texts:
                    body.append("-- %s --" % token)
                    body.append(text.strip())
                    body.append("")
            else:
                body.append("(no license text available)")
                body.append("")
            sections.append("\n".join(body))

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        if title:
            f.write(title + "\n")
        if revision:
            f.write("Pkg.Revision=%s\n" % revision)
        if title or revision:
            f.write("\n")
        f.write("This software depends on external packages and source code.\n")
        f.write("The applicable license information is listed below:\n\n")
        f.write(("\n" + "-" * 4 + "\n\n").join(sections))
        f.write("\n")

    return len(seen_packages), missing


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", type=Path, help="SPDX 3.0 JSON-LD file(s)")
    parser.add_argument("-o", "--output", required=True, type=Path, help="Output NOTICE file path")
    parser.add_argument("--common-license-dir", required=True, type=Path,
                         help="Directory of full license texts keyed by SPDX ID "
                              "(bitbake's COMMON_LICENSE_DIR, i.e. meta/files/common-licenses)")
    parser.add_argument("--title", default=None,
                         help="Optional heading line written at the top of the NOTICE")
    parser.add_argument("--revision", default=None,
                         help="Optional Pkg.Revision value written under the title")
    parser.add_argument("--strict", action="store_true",
                         help="Exit non-zero if any license text could not be resolved")
    args = parser.parse_args()

    count, missing = render_notice(args.inputs, args.common_license_dir, args.output,
                                   title=args.title, revision=args.revision)

    # Summary goes to stdout; stderr is reserved for problems so callers can
    # treat any stderr output as a warning.
    print("Wrote %s: %d package(s), %d unresolved license reference(s)"
          % (args.output, count, len(missing)))
    if missing:
        print("Unresolved: %s" % ", ".join(sorted(missing)), file=sys.stderr)
        if args.strict:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
